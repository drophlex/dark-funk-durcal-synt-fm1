# a hint ("[K1]SLOT[OCT+]SAVE") is drawn word by word (ui_help.c help_parse): its words are the keys, not the hint
import re
ES = {k: v for k, v in ES.items() if not re.match(r'^\[[^\]]+\][^ ]', k)}
# keep only strings the device can draw (ASCII)
for k, v in ES.items():
    assert all(32 <= ord(c) < 127 for c in k + v), (k, v)
# a translation must never itself be an English key with another meaning (no double translation)
bad = [v for k, v in ES.items() if v in ES and ES[v] != v and v != k]
assert not bad, bad
items = sorted(ES.items(), key=lambda kv: kv[0].encode())
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* DARK FUNK DURCAL: the screen in Spanish (generated by tools/gen_lang.py; do not edit). Every text drawn (gfx.c text_w,",
       " * text_run) and every message (ui.c ui_say) whose words are a key here reads in Spanish while lang_es is set",
       " * (DFD NEXT page > K3 LANG, kept in the settings: ui.c ui_idle bit 7). Exact matches only, binary search */",
       "static uint8_t lang_es;",
       "typedef struct { const char *en, *es; } lang_pair_t;",
       "static const lang_pair_t LANG_ES[] = {"]
for k, v in items:
    out.append("    {%s, %s}," % (q(k), q(v)))
out += ["};",
        "#define LANG_N (sizeof LANG_ES / sizeof LANG_ES[0])",
        "static int lang_cmp(const char *a, const char *b)",
        "{",
        "    while (*a && *a == *b) { a++; b++; }",
        "    return (int)(uint8_t)*a - (int)(uint8_t)*b;",
        "}",
        "static const char *lang_tr(const char *s)",
        "{",
        "    uint32_t lo = 0, hi = LANG_N;",
        "    if (!lang_es || !s || !s[0])",
        "        return s;",
        "    while (lo < hi) {",
        "        uint32_t m = (lo + hi) / 2u;",
        "        int c = lang_cmp(s, LANG_ES[m].en);",
        "        if (!c)",
        "            return LANG_ES[m].es;",
        "        if (c > 0)",
        "            lo = m + 1u;",
        "        else",
        "            hi = m;",
        "    }",
        "    return s;",
        "}", ""]
dst = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "lang.c")
open(dst, "w").write("\n".join(out))
print(len(items), "entries ->", os.path.normpath(dst))
